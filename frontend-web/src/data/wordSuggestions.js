export function findTypingSuggestions(query, field = 'term', extraCards = [], limit = 5) {
  const q = (query || '').trim().toLowerCase();
  if (q.length < 2) return [];

  const merged = [...WORD_SUGGESTION_ENTRIES];
  for (const c of extraCards) {
    if (c?.term?.trim() && c?.definition?.trim()) {
      const exists = merged.some(
        (m) => m.term.toLowerCase() === c.term.trim().toLowerCase()
      );
      if (!exists) {
        merged.push({ term: c.term.trim(), definition: c.definition.trim() });
      }
    }
  }

  const startsWithMatches = [];
  const containsMatches = [];

  for (const item of merged) {
    const target = (field === 'definition' ? item.definition : item.term).toLowerCase();
    const other = (field === 'definition' ? item.term : item.definition).toLowerCase();
    if (target === q) continue; // exact already typed

    if (target.startsWith(q)) {
      startsWithMatches.push(item);
    } else if (target.includes(q) || other.includes(q)) {
      containsMatches.push(item);
    }
  }

  return [...startsWithMatches, ...containsMatches].slice(0, limit);
}
